import fs from 'node:fs';

const dir = 'D:/ds workpart/稼轩行迹/_build/';
const outDir = 'D:/ds workpart/稼轩行迹/js/';
fs.mkdirSync(outDir, { recursive: true });

// ---- projection: lon 101..123.5 -> x 0..1000 ; lat 41.5..17.5 -> y 0..720
const LON0 = 101, LON1 = 123.5, LAT0 = 41.5, LAT1 = 17.5;
const W = 1000, H = 720;
const px = (lon) => ((lon - LON0) / (LON1 - LON0)) * W;
const py = (lat) => ((LAT0 - lat) / (LAT0 - LAT1)) * H;

const inside = (lon, lat) => lon >= LON0 - 3 && lon <= LON1 + 3 && lat >= LAT1 - 3 && lat <= LAT0 + 3;

function simplify(points, tol) {
  if (points.length < 3) return points;
  const sqTol = tol * tol;
  const sqDistToSeg = (p, a, b) => {
    let x = a[0], y = a[1];
    let dx = b[0] - x, dy = b[1] - y;
    if (dx !== 0 || dy !== 0) {
      const t = ((p[0] - x) * dx + (p[1] - y) * dy) / (dx * dx + dy * dy);
      if (t > 1) { x = b[0]; y = b[1]; } else if (t > 0) { x += dx * t; y += dy * t; }
    }
    dx = p[0] - x; dy = p[1] - y;
    return dx * dx + dy * dy;
  };
  const sqSegDist = (p, a, b) => sqDistToSeg(p, a, b);
  const getSqSegDist = sqSegDist;
  const simplifyDPStep = (pts, first, last, out, tol) => {
    let maxSqDist = tol, index = -1;
    for (let i = first + 1; i < last; i++) {
      const sqDist = getSqSegDist(pts[i], pts[first], pts[last]);
      if (sqDist > maxSqDist) { index = i; maxSqDist = sqDist; }
    }
    if (index > -1) {
      if (index - first > 1) simplifyDPStep(pts, first, index, out, tol);
      out.push(pts[index]);
      if (last - index > 1) simplifyDPStep(pts, index, last, out, tol);
    }
  };
  const out = [points[0]];
  simplifyDPStep(points, 0, points.length - 1, out, sqTol);
  out.push(points[points.length - 1]);
  return out;
}

const fmt = (n) => Math.round(n * 10) / 10;
function ringToPath(ring, tol = 0.7, closed = true) {
  let pts = ring.map(([lon, lat]) => [px(lon), py(lat)]);
  // keep only if intersects our frame generously
  const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
  if (Math.max(...xs) < -40 || Math.min(...xs) > W + 40 || Math.max(...ys) < -40 || Math.min(...ys) > H + 40) return '';
  pts = simplify(pts, tol);
  const d = pts.map((p, i) => (i === 0 ? 'M' : 'L') + fmt(p[0]) + ' ' + fmt(p[1])).join('');
  return d + (closed ? 'Z' : '');
}

// ---- land
const chn = JSON.parse(fs.readFileSync(dir + 'chn.geo.json', 'utf8'));
const twn = JSON.parse(fs.readFileSync(dir + 'twn.geo.json', 'utf8'));
const landRings = [];
const collect = (geom) => {
  if (geom.type === 'Polygon') geom.coordinates.forEach(r => landRings.push(r));
  else if (geom.type === 'MultiPolygon') geom.coordinates.forEach(p => p.forEach(r => landRings.push(r)));
};
chn.features.forEach(f => collect(f.geometry));
twn.features.forEach(f => collect(f.geometry));

// mainland = biggest ring; islands = rest
const withArea = landRings.map(r => {
  let a = 0;
  for (let i = 0; i < r.length - 1; i++) a += r[i][0] * r[i + 1][1] - r[i + 1][0] * r[i][1];
  return { r, a: Math.abs(a / 2) };
}).sort((x, y) => y.a - x.a);

const mainland = withArea[0].r;
const islands = withArea.slice(1).map(o => o.r).filter(r => {
  const lon = r[0][0], lat = r[0][1];
  return inside(lon, lat);
});

const landPath = ringToPath(mainland, 0.55);
const islandPaths = islands.map(r => ringToPath(r, 0.5)).filter(Boolean);

// ---- rivers
const rivers = JSON.parse(fs.readFileSync(dir + 'ne_50m_rivers.geojson', 'utf8'));
const want = {
  huanghe: ['Huang'],
  changjiang: ['Chang Jiang', 'Yangtze', 'Jinsha', 'Tongtian', 'Tuotuo'],
  han: ['Han'],
  gan: ['Gan'],
  yuan: ['Yuan'],
  min: ['Min'],
  xi: ['Xi'],
};
const riverPaths = {};
for (const [key, names] of Object.entries(want)) {
  const segs = [];
  for (const f of rivers.features) {
    if (!names.includes(f.properties.name)) continue;
    const g = f.geometry;
    const lines = g.type === 'LineString' ? [g.coordinates] : g.type === 'MultiLineString' ? g.coordinates : [];
    for (const line of lines) {
      if (!line.some(c => inside(c[0], c[1]))) continue;
      const d = ringToPath(line, 0.6, false);
      if (d) segs.push(d);
    }
  }
  riverPaths[key] = segs.join('');
}

// ---- Huai river hand-drawn (Natural Earth 50m has no Huai)
const huaiLonLat = [[113.2, 32.35], [113.9, 32.25], [114.8, 32.35], [115.6, 32.55], [116.4, 32.75], [117.2, 32.95], [118.0, 33.15], [118.8, 33.35], [119.5, 33.6], [120.3, 34.05]];
riverPaths.huai = ringToPath(huaiLonLat, 0, false);

// ---- Xiang river hand-drawn (not in dataset)
const xiangLonLat = [[112.6, 26.1], [112.7, 26.9], [112.9, 27.6], [113.0, 28.2], [112.95, 28.8], [112.8, 29.4]];
riverPaths.xiang = ringToPath(xiangLonLat, 0, false);

const out = `// generated by _build/build-map.mjs — do not edit by hand
window.MAP_GEO = {
  lon0: ${LON0}, lon1: ${LON1}, lat0: ${LAT0}, lat1: ${LAT1}, w: ${W}, h: ${H},
  land: ${JSON.stringify(landPath)},
  islands: ${JSON.stringify(islandPaths)},
  rivers: ${JSON.stringify(riverPaths, null, 2)},
};
`;
fs.writeFileSync(outDir + 'map-geometry.js', out);
